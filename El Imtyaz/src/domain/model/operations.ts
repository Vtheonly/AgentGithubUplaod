/**
 * Comparator — sorts alerts by priority (urgent first), then by creation
 * date (newest first) within the same priority. Stable.
 */
export function sortAlertsByPriority<
  T extends { priority: AlertPriority; createdAt: string }
>(alerts: readonly T[]): T[] {
  return [...alerts].sort((a, b) => {
    const pdiff = ALERT_PRIORITY_WEIGHT[b.priority] - ALERT_PRIORITY_WEIGHT[a.priority];
    if (pdiff !== 0) return pdiff;
    return new Date(b.createdAt).getTime() - new Date(a.createdAt).getTime();
  });
}

/**
 * Returns true if a given session should see the alert.
 * Broadcast (null targetUserId + null targetRole) → visible to everyone.
 * User-targeted → visible only to that user.
 * Role-targeted → visible to every user with that role.
 */
export function isAlertVisibleTo(alert: AppNotification, session: {
  userId: string;
  role: Role;
}): boolean {
  if (alert.targetUserId && alert.targetRole) {
    return alert.targetUserId === session.userId || alert.targetRole === session.role;
  }
  if (alert.targetUserId) return alert.targetUserId === session.userId;
  if (alert.targetRole) return alert.targetRole === session.role;
  return true; // broadcast
}
