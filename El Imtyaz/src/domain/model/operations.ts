/**
 * Operations / Dashboard domain — KPIs, charts, alerts, notifications.
 * Plan §15 (Dashboard & Analytics).
 *
 * Iteration 9 — Alert & Notification System Overhaul:
 *   - Alerts now carry an explicit priority (low / medium / high / urgent)
 *     so the UI can sort, filter, and rank by urgency.
 *   - Every alert records its origin (source + sourceLabel) so users can
 *     immediately see which module / entity produced the alert.
 *   - Alerts can be targeted to a specific user, a specific role, or
 *     broadcast to everyone (targetUserId / targetRole both null).
 *   - Alerts can carry an optional `triggeredAt` for timers / scheduled
 *     reminders, distinct from the audit `createdAt`.
 *   - A new `createdBy` field makes manual alerts attributable.
 */
import type { AgingBucket } from "./payment";
import type { Role } from "../../core/rbac/roles";

export type NotificationType =
  | "payment_overdue"
  | "expense_pending"
  | "attendance_alert"
  | "homework"
  | "audit"
  | "system"
  | "message"
  | "custom";

/**
 * Priority ranking — Urgent > High > Medium > Low.
 *
 * Used by the Alerts tab to sort alerts by urgency, and by the Topbar
 * bell to surface the most critical unread alerts first.
 */
export type AlertPriority = "low" | "medium" | "high" | "urgent";

/**
 * Origin category — every alert MUST record where it came from.
 *
 * - `system`          : auto-generated by the platform (overdue, expense pending…)
 * - `manual`          : created by a user via the Alert Creator modal
 * - `workflow`        : raised by a workflow execution
 * - `schedule`        : raised by a scheduled timer (calendar reminder, follow-up call)
 * - `audit`           : raised by the audit subsystem
 */
export type AlertSource =
  | "system"
  | "manual"
  | "workflow"
  | "schedule"
  | "audit";

export interface AppNotification {
  readonly id: string;
  readonly title: string;
  readonly body: string;
  readonly type: NotificationType;
  readonly priority: AlertPriority;
  /** Machine-readable source category. */
  readonly source: AlertSource;
  /** Human-readable module / entity name (e.g. "Module Finances", "Paiements"). */
  readonly sourceLabel: string;
  readonly entityType: string | null;
  readonly entityId: string | null;
  /** Target a specific user (by userId). Null = not user-targeted. */
  readonly targetUserId: string | null;
  /** Target a specific role. Null = not role-targeted. */
  readonly targetRole: Role | null;
  /** Scheduled trigger time for timers / reminders (ISO). Null = immediate. */
  readonly triggeredAt: string | null;
  readonly readAt: string | null;
  readonly createdAt: string;
  /** Actor who created the alert (system userId for auto-generated alerts). */
  readonly createdBy: string;
}

