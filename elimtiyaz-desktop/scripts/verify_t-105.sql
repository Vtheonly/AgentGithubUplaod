CREATE TEMP TABLE _v105_map AS
WITH t1 AS (
  SELECT c.xl_row, s.id AS student_id, s.parent_id
  FROM _v105_corpus c
  JOIN students s ON upper(regexp_replace(s.display_name, '\s+', ' ', 'g')) = c.xl_name
  JOIN parents p ON p.id = s.parent_id
  WHERE s.deleted_at IS NULL AND p.deleted_at IS NULL
    AND c.xl_phone <> ''
    AND regexp_replace(regexp_replace(p.primary_phone, '[^0-9]', '', 'g'), '^0+', '', '') = c.xl_phone
  ORDER BY c.xl_row, s.created_at
), t1_rows AS (SELECT DISTINCT xl_row FROM t1)
SELECT c.xl_row, s.id AS student_id, s.parent_id
FROM _v105_corpus c
JOIN students s ON upper(regexp_replace(s.display_name, '\s+', ' ', 'g')) = c.xl_name
JOIN parents p ON p.id = s.parent_id
WHERE s.deleted_at IS NULL AND p.deleted_at IS NULL
  AND c.xl_unique
  AND c.xl_row NOT IN (SELECT xl_row FROM t1_rows)
UNION ALL
SELECT xl_row, student_id, parent_id FROM t1;

CREATE TEMP TABLE _v105_xl AS
SELECT m.parent_id,
  SUM(c.xl_devis + c.xl_dettes - c.xl_regl) AS xl_netdue,
  SUM(c.xl_paid) AS xl_paid,
  SUM(c.xl_creance) AS xl_creance
FROM _v105_map m JOIN _v105_corpus c ON c.xl_row = m.xl_row
GROUP BY m.parent_id;

CREATE TEMP TABLE _v105_db AS
WITH led AS (
  SELECT parent_id,
    SUM(amount) FILTER (WHERE entry_type='charge' AND reverses_id IS NULL) AS charged,
    SUM(amount) FILTER (WHERE entry_type='adjustment' AND reverses_id IS NULL) AS adjusted,
    SUM(amount) AS balance
  FROM ledger_entries GROUP BY parent_id
), pay AS (
  SELECT parent_id, SUM(amount) AS paid FROM payments
  WHERE status NOT IN ('refunded','cancelled') GROUP BY parent_id
), ins AS (
  SELECT parent_id, SUM(amount_due) AS ins_due, SUM(amount_paid) AS ins_paid,
    SUM(GREATEST(0, amount_due - amount_paid - COALESCE(amount_pending,0))) AS ins_remaining,
    count(*) FILTER (WHERE amount_paid > amount_due + 0.01) AS over_applied
  FROM installments GROUP BY parent_id
)
SELECT p.id AS parent_id,
  COALESCE(led.charged,0)+COALESCE(led.adjusted,0) AS netdue,
  COALESCE(led.balance,0) AS balance, COALESCE(pay.paid,0) AS db_paid,
  COALESCE(ins.ins_due,0) AS ins_due, COALESCE(ins.ins_paid,0) AS ins_paid,
  COALESCE(ins.ins_remaining,0) AS ins_remaining, COALESCE(ins.over_applied,0) AS over_applied
FROM parents p LEFT JOIN led ON led.parent_id=p.id LEFT JOIN pay ON pay.parent_id=p.id
LEFT JOIN ins ON ins.parent_id=p.id WHERE p.deleted_at IS NULL;

CREATE TEMP TABLE _v105_j AS
SELECT x.parent_id, x.xl_netdue, x.xl_paid, x.xl_creance,
  d.netdue, d.balance, d.db_paid, d.ins_due, d.ins_paid, d.ins_remaining, d.over_applied
FROM _v105_xl x JOIN _v105_db d ON d.parent_id = x.parent_id;

CREATE TEMP TABLE _v105_res AS
SELECT
  (SELECT count(*) FROM _v105_j) AS parents,
  count(*) FILTER (WHERE abs(xl_paid - db_paid) < 0.5) AS m1_paid_ok,
  count(*) FILTER (WHERE abs(xl_paid - db_paid) >= 0.5) AS m1_paid_bad,
  count(*) FILTER (WHERE abs(xl_netdue - netdue) < 0.5) AS m2_netdue_ok,
  count(*) FILTER (WHERE abs(xl_netdue - netdue) >= 0.5) AS m2_netdue_bad,
  count(*) FILTER (WHERE abs((xl_netdue - xl_paid) - balance) < 0.5) AS m3_balance_ok,
  count(*) FILTER (WHERE abs((xl_netdue - xl_paid) - balance) >= 0.5) AS m3_balance_bad,
  count(*) FILTER (WHERE abs(ins_due - netdue) < 0.5) AS c3_ins_eq_ledger_ok,
  count(*) FILTER (WHERE abs(ins_due - netdue) >= 0.5) AS c3_bad,
  count(*) FILTER (WHERE over_applied = 0) AS c4_no_overapply_ok,
  count(*) FILTER (WHERE over_applied > 0) AS c4_bad,
  count(*) FILTER (WHERE abs(ins_remaining - GREATEST(0, balance)) < 0.5) AS c5_inv4_ok,
  count(*) FILTER (WHERE abs(ins_remaining - GREATEST(0, balance)) >= 0.5) AS c5_bad
FROM _v105_j;

